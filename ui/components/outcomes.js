const WING_FALLBACK = (code, detail) => `W.I.N.G. 已停止，请看游戏画面，处理后点开始续跑（代码 ${code}${detail ? `：${detail}` : ""}）`;

/** Chinese text for an outcome code (``code`` or ``code: details``); anything else is returned unchanged. */
export function outcomeText(reason, task = null) {
  if (typeof reason !== "string" || !reason) return reason;
  const match = /^([a-z][a-z0-9_]*)(?:[:：]\s*(.*))?$/.exec(reason.trim());
  if (!match) return reason;
  if (task === "Shop" && match[1] === "skipped_rules" && match[2]) {
    const reasons = match[2].split(",").map((code) => code.trim());
    if (reasons.every((code) => Object.prototype.hasOwnProperty.call(SHOP_SKIP_TEXT, code))) {
      return `本轮未购买：${reasons.map((code) => SHOP_SKIP_TEXT[code]).join("；")}`;
    }
  }
  if (task === "AutoProduce" && match[2] && WING_DETAIL_TEXT[`${match[1]}:${match[2].trim()}`]) return WING_DETAIL_TEXT[`${match[1]}:${match[2].trim()}`];
  const own = (map) => Object.prototype.hasOwnProperty.call(map, match[1]) ? map[match[1]] : null;
  const taskText = task === "Training" ? TRAINING_OUTCOME_TEXT : task === "AutoProduce" ? { ...WING_OUTCOME_TEXT, ...WING_RUNTIME_TEXT }
    : Object.prototype.hasOwnProperty.call(CLAIM_OUTCOME_TEXT, task) ? CLAIM_OUTCOME_TEXT[task] : null;
  const text = (taskText && own(taskText)) || own(OUTCOME_TEXT);
  if (!text) return task === "AutoProduce" ? WING_FALLBACK(match[1], match[2]) : reason;
  return match[2] ? `${text}（${match[2]}）` : text;
}
