"""say "Halo" readers (H2b): pure parsers over OCR boxes plus ``read`` for one screen.

ROIs are the ``SC.Wing.Read.Halo.*`` nodes generated by ``tools/wing_nav_build.py`` (measured on the H1 frames of
2026-11-01). Every value that does not read cleanly stays None; the policy stops on what it needs and cannot read.
"""
from __future__ import annotations

import re
from typing import Iterable, Sequence

Texts = Iterable[tuple]
R = "SC.Wing.Read.Halo."

# Header advice bar: nine icons, "xN" under each, slot centres every ~35.3 px from x 647 (H1 frames).
ADVICE_KEYS = ("vo", "da", "vi", "me", "hirameki", "rest", "work", "limit", "best")
ADVICE_X0, ADVICE_PITCH = 647.0, 35.3
# Hub bottom-left button: what the week's main button opens.
HUB_BUTTONS = (("final_live", r"ファイナル"), ("first_live", r"ファースト"), ("produce", r"(プ|ブ)ロデュ"))
HALO_READ_SCREENS = ("HaloHub", "HaloLesson", "HaloAudition", "HaloPractice", "HaloLiveSelect", "HaloTeamInfo",
                     "BookSelect", "BookHistory", "BookPreset", "BookPicker", "HaloGrowth", "HaloRecruit",
                     "HaloTeamEdit", "HaloLeaveConfirm")
LEAVE_X0, LEAVE_PITCH = 401, 245          # チーム編集 「離脱させる」 centres under members 2-5 (live 2026-11-15)
_COUNT = re.compile(r"^[xX×]\s*(\d{1,2})")


def _clean(text: str) -> str:
    return re.sub(r"\s+", "", str(text)).replace("％", "%")     # H1 チーム情報: 「0％」


def _cx(box: Sequence[int]) -> float:
    return box[0] + box[2] / 2


def parse_advice(texts: Texts) -> dict | None:
    """{"vo": n, ..., "best": n} from the header bar; None unless all nine slots read exactly once."""
    out: dict[str, int] = {}
    for text, box in texts:
        m = _COUNT.match(_clean(text))
        if not m:
            continue
        slot = round((_cx(box) - ADVICE_X0) / ADVICE_PITCH)
        if not 0 <= slot < len(ADVICE_KEYS) or ADVICE_KEYS[slot] in out:
            return None
        out[ADVICE_KEYS[slot]] = int(m.group(1))
    return out if len(out) == len(ADVICE_KEYS) else None


def parse_affection(texts: Texts) -> dict:
    """「Lv.N NEXTあと M」 -> {"level": N, "next": M} (OCR reads NEXT as MEXT)."""
    joined = "".join(_clean(t) for t, _ in sorted(texts, key=lambda tb: tb[1][0]))
    level = re.search(r"Lv\.?([0-9])", joined)
    nxt = re.search(r"あと(\d{1,3})", joined)
    return {"level": int(level.group(1)) if level else None, "next": int(nxt.group(1)) if nxt else None}


# 親愛度 needed for the next Lv (H1 trace: +10 per audition win, +5 First Live, 110 on 社長からの評価 at Lv5 あと40).
AFFECTION_NEXT_AT = {0: 1, 1: 25, 2: 50, 3: 75, 4: 100, 5: 150}


def affection_value(affection: dict | None) -> int | None:
    """親愛度 from 「Lv.N NEXTあと M」; None when unread or above the traced levels."""
    level, nxt = (affection or {}).get("level"), (affection or {}).get("next")
    if level not in AFFECTION_NEXT_AT or not isinstance(nxt, int):
        return None
    value = AFFECTION_NEXT_AT[level] - nxt
    return value if value >= AFFECTION_NEXT_AT.get(level - 1, 0) else None


def parse_hub_button(texts: Texts) -> str | None:
    joined = "".join(_clean(t) for t, _ in texts)
    return next((name for name, pattern in HUB_BUTTONS if re.search(pattern, joined)), None)


def parse_percent(texts: Texts) -> int | None:
    """The one 「N%」 value (0–100) in the boxes; None when absent or ambiguous."""
    found = {int(m.group(1)) for t, _ in texts for m in [re.search(r"(\d{1,3})\s*%", _clean(t))] if m}
    found = {v for v in found if 0 <= v <= 100}
    return found.pop() if len(found) == 1 else None


def parse_fans(texts: Texts) -> int | None:
    """Audition reward bubble 「+65000」."""
    found = [int(m.group(1).replace(",", "")) for t, _ in texts for m in [re.search(r"\+([\d,]{3,7})", _clean(t))] if m]
    return found[0] if len(found) == 1 else None


def parse_total_fans(texts: Texts) -> int | None:
    """Schedule page footer: the run's fan total 「114,204」 (right of the green people icon)."""
    found = [int(t.replace(",", "")) for t in (_clean(t) for t, _ in texts) if re.fullmatch(r"\d{1,3}(,\d{3})*|\d{1,7}", t)]
    return found[0] if len(found) == 1 else None


def parse_card_note(texts: Texts) -> str | None:
    """Practice card footer: "short" (必要なアドバイスが不足), "best" (ベストアドバイスで代用可能) or None (enough)."""
    joined = "".join(_clean(t) for t, _ in texts)
    if "不足" in joined:
        return "short"
    if "代用" in joined:
        return "best"
    return None


def parse_live_rates(texts: Texts) -> list[int | None]:
    """目標ライブ挑戦確認: the three cards' 成功率 top to bottom (card centres y ~196 / 371 / 547)."""
    rates: list[int | None] = [None, None, None]
    for text, box in texts:
        m = re.search(r"(\d{1,3})\s*%", _clean(text))
        if not m:
            continue
        slot = min(range(3), key=lambda i: abs(box[1] + box[3] / 2 - (196 + 175 * i)))
        rates[slot] = int(m.group(1)) if rates[slot] is None else -1
    return [r if r is not None and 0 <= r <= 100 else None for r in rates]


def parse_completion(texts: Texts) -> int | None:
    """チーム情報 「チーム完成度：N%」."""
    joined = "".join(_clean(t) for t, _ in texts)
    m = re.search(r"完成度[:：]?(\d{1,3})%", joined)
    return int(m.group(1)) if m and int(m.group(1)) <= 100 else None


# Lesson/work tiles (x ranges) and the room ids W.I.N.G. uses for the same six tiles.
ROOM_TILES = ((278, 440), (443, 603), (606, 766), (769, 930), (933, 1094), (1097, 1258))
ROOM_IDS = ("lesson_vo", "lesson_da", "lesson_vi", "work_radio", "work_talk", "work_magazine")
HEADER_ICON_X = (641, 677, 712, 748, 784, 820, 855, 891, 927)
METER_UNDERSIDES = (((145, 137, 144), 22), ((254, 159, 43), 30))    # grey; orange under a ringed (promise) portrait


def _runs(mask, lo: int, hi: int) -> list[tuple[int, int]]:
    out, start = [], None
    for i, v in enumerate(list(mask) + [False]):
        if v and start is None:
            start = i
        if not v and start is not None:
            if lo <= i - start <= hi:
                out.append((start, i - 1))
            start = None
    return out


def advice_refs(image):
    """The nine header icon colours of this frame (median of the more saturated half of each icon's centre)."""
    import numpy as np
    out = []
    for x in HEADER_ICON_X:
        patch = np.asarray(image)[36:50, x - 5:x + 6, :3].reshape(-1, 3).astype(float)
        sat = (patch.max(1) - patch.min(1)) / np.maximum(patch.max(1), 1)
        out.append(np.median(patch[sat >= np.percentile(sat, 50)], axis=0))
    return np.array(out)


def read_room_advice(image) -> list[list[str]] | None:
    """Advice each lesson/work tile gives: one entry per companion idol (its icon above the portrait), matched to this
    frame's header icon colours. Companions are found by their bond meter's underside at y 612 (H1 frames: 6/6 lesson
    pages read exactly, ringed promise portraits included). An icon that matches no colour reads "?"."""
    if image is None:
        return None
    import numpy as np
    im = np.asarray(image)[:, :, :3].astype(float)
    refs = advice_refs(image)
    rooms = []
    for a, b in ROOM_TILES:
        row = im[612, a:b]
        under = np.zeros(len(row), dtype=bool)
        for colour, tol in METER_UNDERSIDES:
            under |= np.linalg.norm(row - np.array(colour), axis=1) < tol
        kinds = []
        for s, e in _runs(under, 18, 36):
            cx = a + (s + e) // 2
            patch = im[566:584, cx - 16:cx + 2].reshape(-1, 3)
            d = np.linalg.norm(patch[:, None, :] - refs[None], axis=2)
            near = d.min(1) < 35
            kinds.append(ADVICE_KEYS[int(np.bincount(d.argmin(1)[near], minlength=9).argmax())]
                         if near.sum() >= 15 else "?")
        rooms.append(kinds)
    return rooms


# Carousel page dots (H1 frames): audition row y 529, practice row y 172; 27 px apart, centred on x ~767; the shown card's
# dot is pink, the others dark.
DOT_ROWS = {"HaloAudition": 529, "HaloPractice": 172}
DOT_PITCH, DOT_CENTRE = 27, 767
DOT_DARK, DOT_PINK = (76, 66, 72), (255, 92, 134)


def read_dots(image, y: int) -> dict | None:
    """{"count": n, "selected": i | None} from one dot row; None unless an evenly spaced row is centred on the page.
    ``selected`` is None mid-slide (no pink dot)."""
    if image is None:
        return None
    import numpy as np
    row = np.asarray(image)[y, 540:1000, :3].astype(float)
    dark = np.linalg.norm(row - np.array(DOT_DARK), axis=1) < 30
    pink = np.linalg.norm(row - np.array(DOT_PINK), axis=1) < 40
    runs = _runs(dark | pink, 6, 13)
    chains, chain = [], runs[:1]
    for prev, run in zip(runs, runs[1:]):
        if abs((run[0] + run[1]) / 2 - (prev[0] + prev[1]) / 2 - DOT_PITCH) <= 2:
            chain.append(run)
        else:
            chains.append(chain)
            chain = [run]
    chains.append(chain)
    for chain in chains:
        if chain and abs(540 + (chain[0][0] + chain[-1][1]) / 2 - DOT_CENTRE) <= 6:
            selected = [i for i, (s, e) in enumerate(chain) if pink[s:e + 1].mean() > .5]
            return {"count": len(chain), "selected": selected[0] if len(selected) == 1 else None}
    return None


def parse_live_selected(texts: Texts) -> int | None:
    """目標ライブ: index of the card tagged 「選択中」 (tag ~53 px above the card centre)."""
    slots = {min(range(3), key=lambda i: abs(box[1] + box[3] / 2 + 53 - (196 + 175 * i)))
             for text, box in texts if "選択" in _clean(text)}
    return slots.pop() if len(slots) == 1 else None


# ---- setup (H2c batch 2): プロデュース選択 caption, ノウハウブック選択 (H1 frames 2026-11-01) and its 設定履歴 /
# プリセット pages (weekly Auto frames 2026-10-29; the same page widgets, there with S.T.E.P.'s three slots).
SCENARIO_CAPTIONS = (("halo", r"Halo"), ("step", r"S\.?T\.?E\.?P"), ("wing", r"W\.?I\.?N\.?G"),
                     ("fans", r"感謝祭"), ("grad", r"G\.?R\.?A\.?D"), ("lp", r"Landing"))
# Slot 1's four bonuses (BOOK_STATS[0] of agent/core/weekly_auto.py; H1: +150 [584,526] / +50 [690,528] / +50 [588,559]
# / +40 [692,563]).
BOOK_SLOT1 = {"vo": (580, 524, 75, 38), "da": (680, 524, 75, 38), "vi": (580, 556, 75, 38), "me": (680, 556, 75, 38)}
BOOK_BUTTONS = (("auto", r"おまかせ", (540, 632, 165, 50)), ("history", r"設定履", (718, 632, 162, 50)),
                ("decide", r"^(決|决)定$", (1110, 625, 135, 70)), ("preset", r"^プリセット$", (25, 155, 160, 40)))
HISTORY_DATE = (940, 100, 240, 40)
HISTORY_CALL = (1005, 152, 126, 52)
PRESET_LABEL = ((325, 92, 165, 40), (325, 277, 165, 40))
PRESET_SET = ((760, 147, 115, 46), (760, 332, 115, 46))


def _in(box: Sequence[int], rect: Sequence[int], pad: int = 6) -> bool:
    x, y, w, h = rect
    cx, cy = box[0] + box[2] / 2, box[1] + box[3] / 2
    return x - pad <= cx <= x + w + pad and y - pad <= cy <= y + h + pad


def parse_caption(texts: Texts) -> str | None:
    """Scenario under the stage picture (「say "Halo"編」, 「S.T.E.P.編」 …) -> "halo"/"step"/...; None unless one."""
    joined = "".join(_clean(t) for t, _ in texts)
    if "編" not in joined:
        return None
    hits = {key for key, pattern in SCENARIO_CAPTIONS if re.search(pattern, joined, re.I)}
    return hits.pop() if len(hits) == 1 else None


def parse_book_page(prompt: Texts, slot: Texts, locked: Texts, footer: Texts, top: Texts = ()) -> dict:
    """ノウハウブック選択: slot 1 empty / filled (its four bonuses), the Halo one-book layout and the footer buttons."""
    prompt_text = "".join(_clean(t) for t, _ in prompt)
    stats: dict[str, int] = {}
    for text, box in slot:
        m = re.fullmatch(r"\+(\d{1,4})", _clean(text))
        keys = [k for k, rect in BOOK_SLOT1.items() if _in(box, rect, 4)]
        if m and len(keys) == 1 and keys[0] not in stats:
            stats[keys[0]] = int(m.group(1))
    empty = "選択してください" in prompt_text
    filled = len(stats) == len(BOOK_SLOT1)
    locked_count = sum("使用できません" in _clean(t) for t, _ in locked)
    one_book = "1つ選択" in prompt_text or locked_count == 2
    three_books = "3つ選択" in prompt_text
    labels = list(footer) + list(top)
    buttons = {key: any(re.search(pattern, _clean(t)) and _in(b, rect) for t, b in labels)
               for key, pattern, rect in BOOK_BUTTONS}
    return {"slot1": None if empty == filled else ("filled" if filled else "empty"),
            "stats": stats if filled else None,
            "layout": "halo" if one_book and not three_books else ("three" if three_books else None),
            "buttons": buttons}


# Book picker (带书「ノウハウ页指定」): weekly Auto's measured layout (agent/core/weekly_auto.py PICKER_*, DETAIL_*).
PICKER_COLS, PICKER_ROWS, PICKER_PITCH, PICKER_ORIGIN = 5, 3, 138, (535, 180)
PICKER_EVAL = (48, 75, 64, 36)
PICKER_BG = (4, 50, 10, 30)
PICKER_CHECK = (76, -6, 38, 36)
PICKER_BG_MIN = 200
PICKER_CHECK_PINK = 300
PICKER_SORT = (965, 100, 165, 40)
PICKER_ORDER = (1140, 98, 100, 45)
DETAIL_TITLE = (145, 92, 300, 36)
DETAIL_STATS = {"vo": (195, 134, 70, 34), "da": (350, 134, 70, 34), "vi": (195, 170, 70, 32), "me": (350, 170, 70, 32)}


def parse_leave_buttons(texts: Texts) -> list:
    """チーム編集: per member slot 2-5 whether its 「離脱させる」 shows."""
    out = [False] * 4
    for t, box in texts:
        n = round((_cx(box) - LEAVE_X0) / LEAVE_PITCH)
        if "離脱" in _clean(t) and 0 <= n < 4 and abs(_cx(box) - (LEAVE_X0 + LEAVE_PITCH * n)) < 60:
            out[n] = True
    return out


def parse_picker(header: Texts, tiles: Texts, image=None) -> dict:
    """Picker first screen: sort key / order and per tile (r, c) its 評価値, grey (not selectable) and ✓ (selected).
    Pixel checks need ``image``; without it grey/selected stay None."""
    from agent.core import weekly_auto as wa
    sort = next((_clean(t) for t, b in header if _in(b, PICKER_SORT, 8)), None)
    order = next((_clean(t) for t, b in header if _in(b, PICKER_ORDER, 8)), None)
    out = []
    for r in range(PICKER_ROWS):
        for c in range(PICKER_COLS):
            x, y = PICKER_ORIGIN[0] + PICKER_PITCH * c, PICKER_ORIGIN[1] + PICKER_PITCH * r
            ex, ey, ew, eh = PICKER_EVAL
            values = [int(m.group(0)) for t, b in tiles if _in(b, (x + ex, y + ey, ew, eh), 6)
                      for m in [re.fullmatch(r"\d{1,4}", _clean(t))] if m]
            grey = selected = None
            if image is not None:
                bx, by, bw, bh = PICKER_BG
                cx, cy, cw, ch = PICKER_CHECK
                grey = float(wa._patch(image, (x + bx, y + by, bw, bh)).mean()) < PICKER_BG_MIN
                # wing frames are RGB; weekly_auto.check_pixels reads BGR
                selected = wa.check_pixels(image[..., ::-1], (x + cx, y + cy, cw, ch)) >= PICKER_CHECK_PINK
            out.append({"r": r, "c": c, "eval": values[0] if len(values) == 1 else None, "grey": grey,
                        "selected": selected})
    return {"sort": sort, "order": order, "tiles": out}


def parse_picker_detail(texts: Texts) -> dict:
    """The detail panel of the book last tapped: title and Vo/Da/Vi/Me."""
    title = "".join(_clean(t) for t, b in texts if _in(b, DETAIL_TITLE, 4)) or None
    stats = {}
    for key, rect in DETAIL_STATS.items():
        values = [int(m.group(0)) for t, b in texts if _in(b, rect, 4) for m in [re.fullmatch(r"\d{1,4}", _clean(t))] if m]
        stats[key] = values[0] if len(values) == 1 else None
    return {"title": title, "stats": stats}


def parse_history(texts: Texts) -> dict:
    """設定履歴: the newest set's date and its 「呼び出し」."""
    date = next((m.group(0) for t, b in texts if _in(b, HISTORY_DATE)
                 for m in [re.search(r"\d{4}/\d{1,2}/\d{1,2}", _clean(t))] if m), None)
    call = any("呼び出し" in _clean(t) and _in(b, HISTORY_CALL) for t, b in texts)
    return {"date": date, "call": call}


def parse_presets(texts: Texts) -> list[dict]:
    """プリセット dialog: per row (プリセット1, 2) its label and whether 「セット」 is shown."""
    return [{"label": any(re.fullmatch(rf"プリセット{i + 1}", _clean(t)) and _in(b, PRESET_LABEL[i]) for t, b in texts),
             "set": any(_clean(t) == "セット" and _in(b, PRESET_SET[i]) for t, b in texts)} for i in range(2)]


def read(screen: str, evaluator, frame) -> dict:
    """Every Halo field ``screen`` shows; unread values are None."""
    from agent.core import wing_screen as wsc
    T = lambda name: evaluator.texts(R + name, frame) if R + name in evaluator.nodes else ()  # noqa: E731
    out: dict = {}
    if screen in ("HaloHub", "HaloLesson", "HaloAudition", "HaloPractice"):
        header = wsc.read_header(evaluator, frame)
        season_texts = "".join(_clean(t) for t, _ in evaluator.texts("SC.Wing.Read.Hub.Season", frame)) \
            if "SC.Wing.Read.Hub.Season" in evaluator.nodes else ""
        out["season"] = "camp" if "合宿" in season_texts else header["season"]
        out["weeks_left"] = header["weeks_left"]
        fill = wsc.stamina_fill(frame.image)
        out["stamina_pct"] = None if fill is None else round(fill * 100)
        out["advice"] = parse_advice(T("Advice"))
        out["affection"] = parse_affection(T("Affection"))
        out["affection_value"] = affection_value(out["affection"])
    if screen == "HaloHub":
        out["hub_button"] = parse_hub_button(T("HubButton"))
    if screen == "HaloLesson":
        advice = read_room_advice(frame.image)
        selected = {r["id"]: r["selected"] for r in wsc.read_rooms(evaluator, frame)}
        out["rooms"] = None if advice is None else [
            {"id": rid, "advice": kinds, "selected": selected.get(rid)} for rid, kinds in zip(ROOM_IDS, advice)]
    if screen in ("HaloAudition", "HaloPractice"):
        out["card_rate"] = parse_percent(T("CardRate"))
        out["card_name"] = "".join(_clean(t) for t, _ in T("CardName")) or None
    if screen in DOT_ROWS:
        out["dots"] = read_dots(frame.image, DOT_ROWS[screen])
    if screen == "HaloAudition":
        out["card_fans"] = parse_fans(T("CardFans"))
        out["fans"] = parse_total_fans(T("Fans"))
    if screen == "HaloPractice":
        out["card_note"] = parse_card_note(T("CardNote"))
    if screen == "HaloLiveSelect":
        out["live_rates"] = parse_live_rates(T("LiveRates"))
        out["live_selected"] = parse_live_selected(T("LiveSelected"))
    if screen == "HaloTeamInfo":
        out["completion"] = parse_completion(T("Completion"))
    if screen == "HaloRecruit":
        # the selected candidate already joined (header 「勧誘済」, チームに勧誘 greyed): H2d live 2026-11-05
        out["recruited"] = any("誘済" in _clean(t) for t, _ in T("RecruitStatus"))
        out["recruit_name"] = "".join(_clean(t) for t, _ in T("RecruitName")) or None
        tiles = [False] * 5
        for t, box in T("RecruitTiles"):
            n = int((_cx(box) - 450) // 150)
            if "誘済" in _clean(t) and 0 <= n < 5:
                tiles[n] = True
        out["recruit_tiles"] = tiles
    if screen == "HaloGrowth":
        from agent.core import halo_growth
        out["growth"] = halo_growth.read(list(T("GrowthTop")) + list(T("GrowthRows")) + list(T("GrowthBottom")),
                                         frame.image)
    if screen == "BookSelect":
        out["book"] = parse_book_page(T("BookPrompt"), T("BookSlot"), T("BookLocked"), T("BookFooter"), T("BookTop"))
    if screen == "BookHistory":
        out["history"] = parse_history(T("HistoryTop"))
    if screen == "HaloTeamEdit":
        out["leave_buttons"] = parse_leave_buttons(T("LeaveButtons"))
    if screen == "HaloLeaveConfirm":
        question = "".join(_clean(t) for t, _ in T("LeaveQuestion"))
        out["leave_question"] = "離脱させますか" in question
        out["leave_name"] = question.split("をチーム")[0] if "をチーム" in question else None
    if screen == "BookPicker":
        out["picker"] = parse_picker(T("PickerHeader"), T("PickerTiles"), frame.image)
        out["picker_detail"] = parse_picker_detail(T("PickerDetail"))
    if screen == "BookPreset":
        out["presets"] = parse_presets(T("PresetRows"))
    return out


def read_setup_select(T) -> dict:
    """プロデュース選択 (both tabs): the scenario caption, the 特化プロデュース tab label and 次へ."""
    return {"caption": parse_caption(T(R + "Caption")),
            "special_tab": any(re.search(r"特化(プ|ブ)ロデュース", _clean(t)) and _in(b, (1015, 85, 155, 32))
                               for t, b in T("SC.Wing.Read.ProduceSelect.Tabs")),
            "next_label": any(re.fullmatch(r"次(へ|入)", _clean(t)) and _in(b, (1110, 632, 135, 60))
                              for t, b in T(R + "SetupNext"))}
