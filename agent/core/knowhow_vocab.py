CORE_MARGIN = 0.10
TYPES = ("Vo", "Da", "Vi")
_STAT_TYPE = {"Vocal": "Vo", "Dance": "Da", "Visual": "Vi"}
SCENARIOS = ("(W.I.N.G.)", "(G.R.A.D.)", "(S.T.E.P.)")

