"""Known ノウハウ row names and snapping of OCR readings onto them.

The detail list OCR is good at the name core but unreliable at the parts that tell siblings apart: the type suffix
「(Vo)/(Da)/(Vi)」 (truncated to 「(V」/「(Vo」, missing), rings ◯/◎ (dropped), tiers +/++/+++ and scenario dots
「(G.R.A.D.)」 (garbled). A string distance cannot decide between siblings (◯ vs ◎ tie at 0.94), so a reading is snapped in
two steps:

1. Core: the reading without type suffix / tier / ring is matched against the known cores (exact, else difflib ratio
   >= ``CORE_MIN`` with a lead of >= ``CORE_MARGIN`` over the next core).
2. Sibling: the type comes from the effect text's stat word (「Vocal+20」 → Vo; a song row's effect is always its own
   type); tier and ring come from the OCR tail when that tail forms a known name, cross-checked against an effect →
   name table learned from clean readings (``EffectTable``). A disagreement is ``ambiguous`` and nothing is snapped.

ShinyColorsDB holds almost none of these names (only the 上限UP panel titles), so the set is open: an unknown reading
stays raw with status ``unknown`` and is listed for the user, whose confirmations (``CONFIRMED_PATH``, private) join
the known names. Names generated by grammar (scenario / combination / audition variants) are plausible, not observed.
"""

from __future__ import annotations

import difflib
import json
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Mapping

