def _known_names() -> frozenset[str]:
    names = set(PLAIN) | set(_ABILITIES)
    names |= {f"{s}({t})" for s in _SONGS + _STEP_GOALS for t in TYPES}
    names |= {f"{base}{'+' * n}" for base in _TIERED for n in range(4)}
    names |= {f"{base}{r}" for base in _RINGED for r in "◯◎"}
    names |= {f"{a}{s}" for a in _ABILITIES for s in SCENARIOS}
    return frozenset(normalize_name(n) for n in names)


KNOWN = _known_names()

_TYPE_TAIL = re.compile(r"\((?:V[oOi0]?|D[a]?|)\)?$|\(?(?:Vo|Da|Vi)\)?$")
_TIER_TAIL = re.compile(r"\++$")


def split(name: str) -> tuple[str, str | None, str]:
    """(core, type, tail) of a normalised name: type = Vo/Da/Vi when a full 「(Xx)」 suffix is present (a truncated one is
    stripped with type None); tail = trailing tier pluses or ring kept verbatim (「++」, 「◎」)."""
    name = normalize_name(name)
    typ = None
    m = re.search(r"\((Vo|Da|Vi)\)$", name)
    if m:
        typ, name = m.group(1), name[:m.start()]
    elif re.search(r"\((V|Vo|Vi|D|Da|VO|vo|vi|da)?$", name) and "(" in name[-4:]:
        name = name[:name.rindex("(")]                  # truncated 「(V」/「(Vo」 at the panel edge
    tail = ""
    m = re.search(r"(\++|[◯◎])$", name)
    if m and not name.endswith(")"):
        tail, name = m.group(1), name[:m.start()]
    return name, typ, tail


# OCR glyph confusions seen in the 2026-10-23 scan (姬 for 姫 in 185 rows, 迪 for 適, 遑 for 達, 令 for 今). Folded on both
# sides for core matching only; the snapped name is always the known spelling.
_FOLD = str.maketrans({"姬": "姫", "迪": "適", "遑": "達", "令": "今"})


def fold(text: str) -> str:
    return text.translate(_FOLD)


def _core_index(names: Iterable[str]) -> dict[str, set[str]]:
    cores: dict[str, set[str]] = defaultdict(set)
    for n in names:
        cores[split(n)[0]].add(n)
    return cores


def effect_type(effect: str | None) -> str | None:
    """Vo/Da/Vi from an effect line that starts with its stat (「Vocal+20」); None when unclear."""
    m = re.match(r"(Vocal|Dance|Visual)\+\d", normalize_name(effect or ""))
    return _STAT_TYPE[m.group(1)] if m else None


def effect_key(effect: str | None) -> tuple[str, ...] | None:
    """The numbers that tell siblings apart, robust to OCR noise in the words: the signed values (「+10%」, 「+20」), else
    the percentages (「5%」, 「10%」 of the 思い出 abilities); duplicated read-overs (「Vocal+20cal+20」) collapse."""
    text = normalize_name(effect or "")
    found = re.findall(r"[+\-]\d+%?", text) or re.findall(r"\d+%", text)
    return tuple(dict.fromkeys(found)) or None


class EffectTable:
    """effect key → names, learned from rows whose reading is exactly a known name. ``lookup`` answers only when the key
    points to exactly one name among the given ones (siblings that share a key cannot be told apart by it)."""

    def __init__(self):
        self.seen: dict[tuple[str, ...], Counter] = defaultdict(Counter)

    def learn(self, name: str, effect: str | None) -> None:
        key = effect_key(effect)
        name = normalize_name(name)
        if key and name in KNOWN:
            self.seen[key][name] += 1

    def names(self, effect: str | None) -> set[str]:
        key = effect_key(effect)
        return set(self.seen.get(key, ())) if key else set()

    def lookup(self, among: Iterable[str], effect: str | None) -> str | None:
        hits = self.names(effect) & set(among)
        return next(iter(hits)) if len(hits) == 1 else None

    def conflicts(self, among: Iterable[str], effect: str | None) -> bool:
        return len(self.names(effect) & set(among)) > 1


@dataclass(frozen=True)
class Snap:
    name: str                 # canonical name, or the raw normalised reading when not snapped
    status: str               # exact | snapped | ambiguous | unknown
    reading: str
    score: float = 1.0
    reason: str = ""

    @property
    def trusted(self) -> bool:
        return self.status in ("exact", "snapped")


class Vocabulary:
    def __init__(self, extra: Iterable[str] = (), table: EffectTable | None = None):
        self.names = frozenset(KNOWN | {normalize_name(n) for n in extra})
        self.cores = _core_index(self.names)
        self.table = table or EffectTable()

    @classmethod
    def load(cls, path: Path = CONFIRMED_PATH, table: EffectTable | None = None) -> "Vocabulary":
        try:
            extra = json.loads(Path(path).read_text(encoding="utf-8")).get("names", [])
        except (OSError, ValueError, AttributeError):
            extra = []
        return cls(extra if isinstance(extra, list) else [], table)

    def _core(self, core: str, effect: str | None) -> tuple[str | None, float, str]:
        if core in self.cores:
            return core, 1.0, ""
        folded = fold(core)
        scored = sorted(((difflib.SequenceMatcher(None, folded, fold(c)).ratio(), c) for c in self.cores), reverse=True)
        if not scored:
            return None, 0.0, "empty"
        best, second = scored[0], (scored[1] if len(scored) > 1 else (0.0, ""))
        if best[0] < CORE_MIN:
            return None, best[0], f"core<{CORE_MIN}:{best[1]}"
        if best[0] - second[0] < CORE_MARGIN:
            # Close cores (「アピールUP(思い出高&低)」 vs 「…(思い出高)」): the effect numbers may name exactly one of them.
            close = [c for r, c in scored if best[0] - r < CORE_MARGIN]
            named = {split(n)[0] for n in self.table.names(effect)} & set(close)
            if len(named) == 1:
                return named.pop(), best[0], "effect"
            return None, best[0], f"core_margin:{best[1]}|{second[1]}"
        return best[1], best[0], ""

    def snap(self, reading: str, effect: str | None = None) -> Snap:
        raw = normalize_name(reading)
        core_raw, typ, tail = split(raw)
        core, score, why = self._core(core_raw, effect)
        if core is None:
            return Snap(raw, "unknown" if why.startswith(("core<", "empty")) else "ambiguous", raw, score, why)
        family = self.cores[core]
        # type: effect stat word wins; a full OCR suffix must agree with it
        typed = {n for n in family if split(n)[1] is not None}
        if typed:
            etype = effect_type(effect)
            if etype and typ and etype != typ:
                return Snap(raw, "ambiguous", raw, score, f"type:{typ}!={etype}")
            typ = etype or typ
            if typ is None:
                return Snap(raw, "ambiguous", raw, score, "type_unknown")
            family = {n for n in family if split(n)[1] == typ}
        elif typ is not None:
            return Snap(raw, "ambiguous", raw, score, f"type_not_expected:{typ}")
        # tier / ring: the learned effect table and the OCR tail must not disagree
        by_effect = self.table.lookup(family, effect)
        candidates = {n for n in family if split(n)[2] == tail}
        if by_effect is not None:
            if candidates and by_effect not in candidates:
                return Snap(raw, "ambiguous", raw, score, f"tail:{tail}!=effect:{by_effect}")
            name = by_effect
        elif len(candidates) == 1:
            name = next(iter(candidates))
            if len(family) > 1 and not tail and self.table.conflicts(family, effect):
                return Snap(raw, "ambiguous", raw, score, "effect_conflict")
            if len(family) > 1 and not tail and any(split(n)[2] in _RING_TAILS for n in family):
                return Snap(raw, "ambiguous", raw, score, "ring_missing")   # 適正 / オールラウンダー need ◯/◎
        else:
            return Snap(raw, "ambiguous", raw, score, f"tail:{tail or '-'}")
        return Snap(name, "exact" if name == raw else "snapped", raw, score)


_RING_TAILS = ("◯", "◎")


def learn_table(books: Iterable[Mapping[str, Any]]) -> EffectTable:
    table = EffectTable()
    for book in books:
        for row in book.get("rows") or ():
            table.learn(row.get("name", ""), row.get("effect"))
    return table
