"""Maa glue for the K3 ノウハウブック一覧 scan (SC.KnowhowScan.*): a full-frame OCR reader bound to the Maa context,
the frame-bound decision recognition and the begin / finish / stop actions. Rules live in ``knowhow_scan``.

**No action here sends input.** The input steps are Pipeline nodes bound to the ``knowhow-scan`` action-table entries
(generated by ``tools/knowhow_scan_build.py``), each guarded by ``SC.KnowhowScan.Want`` and enabled only by the
supervised ``KnowhowScan`` entry of tools/run_tasks.py.

Two modes (``SC.KnowhowScan.Config`` attach ``mode``): ``calibrate`` (``knowhow_calibrate``: measures the wheel steps,
never changes the sort, writes only a private calibration record) and ``scan`` (``knowhow_scan``). Every observed
capture is saved under ``dev_assets/private/knowhow-scan/<mode>-<UTC>/frame-NNNN.png``; the report names that folder.

Output: a private run record under ``dev_assets/private/knowhow-scan/`` (``-partial`` suffix unless every grid tile has
a complete book) and the private inventory + gitignored UI module (``knowhow_books.save_inventory`` /
``export_ui_module``). Partial scans are written too, but flagged: books keep their incomplete unknowns and the grid
coverage is ``complete`` only when proven, so the UI never presents a partial scan as the whole library.
"""
