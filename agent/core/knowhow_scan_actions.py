def _image_digest(image) -> str:
    return hashlib.sha256(image.tobytes()).hexdigest()


PANEL_ROI = (0, 90, 470, 520)       # left detail panel (x, y, w, h)
PANEL_SAME_MAD = 3.0                # live 2026-10-13: empty panel's animated sparkles 0.7; a detail page scroll >= 13


def _same_screen(before, image) -> bool:
    """True when two captures show the same screen apart from the animated background: the grid region settled
    (knowhow_grid.SETTLE_MAD: static pairs 0.1-0.2, tile selection >= 0.9) and the detail panel unchanged. The live
    background animates, so an exact digest never repeated; the slow first observation then outlived the 5 s permit
    TTL on every poll and no open_tile click could pass the frame guard (2026-10-13 kh-full2)."""
    import numpy as np

    if before is None or image is None or getattr(before, "shape", None) != getattr(image, "shape", None):
        return False
    if not kg.settled(before, image):
        return False
    x, y, w, h = PANEL_ROI
    a, b = before[y:y + h, x:x + w, :3].astype(np.int16), image[y:y + h, x:x + w, :3].astype(np.int16)
    return bool(a.size) and float(np.abs(a - b).mean()) <= PANEL_SAME_MAD


class OcrUnavailable(RuntimeError):
    """The native OCR can no longer be called safely (task ending / stopping, or the native call already failed)."""


class ContextOcr:
    """Full-frame OCR through the Maa context (same det+rec model as the K1 calibration).

    The context is the one of the recognition that is running now (``bind``): the Begin action's context belongs to a
    node that has long ended. 2026-10-13 live (kh-full5): ``run_recognition_direct`` raised an access violation inside
    the first observation and the process died natively on the next poll, so after one native failure (or when the task
    is stopping) no further native call is made."""

    def __init__(self, context):
        self.context = context
        self.dead = None

    def bind(self, context):
        if context is not None:
            self.context = context

    def _check(self):
        if self.dead:
            raise OcrUnavailable(self.dead)
        context = self.context
        try:
            if context.tasker.stopping or not context.get_task_job().running:
                raise OcrUnavailable("task_not_running")
        except OcrUnavailable:
            raise
        except Exception as exc:          # cannot prove the context is alive: do not touch native code
            raise OcrUnavailable(f"context_unusable:{type(exc).__name__}") from exc

    def __call__(self, image_rgb):
        import numpy as np
        from maa.pipeline import JOCR, JRecognitionType

        self._check()
        bgr = np.ascontiguousarray(image_rgb[:, :, ::-1])
        height, width = bgr.shape[:2]          # full frame, or a detail-name crop (kb.refine_detail_tokens)
        param = JOCR(expected=[".*"], roi=(0, 0, width, height), threshold=0.0)
        try:
            detail = self.context.run_recognition_direct(JRecognitionType.OCR, param, bgr)
        except Exception as exc:
            self.dead = f"native_ocr_failed:{type(exc).__name__}"
            raise OcrUnavailable(self.dead) from exc
        rows = getattr(detail, "all_results", None) or [] if detail is not None else []
        return [(r.text, tuple(int(v) for v in r.box), float(r.score)) for r in rows if r.text]


class KnowhowScanRuntime:
    def __init__(self, sink=SINK, run_dir=RUN_DIR, clock=None, inventory_path=kb.INVENTORY_PATH,
                 ui_path=kb.UI_MODULE_PATH, write_inventory=True, profile_path=kb.PROFILE_PATH):
        self.sink = sink
        self.run_dir = Path(run_dir)
        self.clock = clock or (lambda: _dt.datetime.now(_dt.timezone.utc))
        self.inventory_path, self.ui_path, self.profile_path = inventory_path, ui_path, profile_path
        self.write_inventory = write_inventory
        self.lock = threading.Lock()
        self.click_history = None  # launcher-provided: () -> the controller's click/wheel history (read only)
        self.reset()

    def reset(self):
        self.mode = None
        self.frames_dir = None
        self.options = None
        self.session = None
        self.cache = None          # (digest, decision, image) of the last observed capture
        self.last = None           # (digest, decision) returned for the most recent capture (``peek``)
        self.fresh = False         # True once that decision was executed: the next capture is observed afresh
        self.unconfirmed = 0       # differing captures observed while an input decision was never confirmed sent
        self.outcome = None
        self.result = None
        self.ocr_failed = None     # reason once the native OCR failed (the scan is then stopped for good)
        self.retries = 0           # denied (never sent) inputs re-tried for the pending decision

    def report(self, outcome, **extra):
        self.outcome = outcome
        payload = {"outcome": outcome, **extra}
        self.sink.add("knowhow_scan", payload)
        LOGGER.info("KnowhowScan: %s", json.dumps(payload, ensure_ascii=False, default=str)[:2000])

    def begin(self, context, p):
        self.reset()
        merged = {}
        try:
            for name in p.get("config_nodes", []):
                merged.update((context.get_node_data(name) or {}).get("attach") or {})
            mode = merged.pop("mode", "scan")
            calibration = merged.pop("calibration", None)
            filter_calibration = merged.pop("filter_calibration", None)
            resume_path = merged.pop("resume_record", None)
            scan_id = ks.validate_scan_id(merged.pop("scan_id", None))
            if mode not in ("scan", "calibrate", "filter_calibrate"):
                raise ValueError(f"mode 须为 scan、calibrate 或 filter_calibrate: {mode}")
            self.options = ks.ScanOptions.from_params(merged)
            calib = kc.CalibrationOptions.from_params(calibration) if mode == "calibrate" else None
            fcalib = kf.FilterCalibrationOptions.from_params(filter_calibration) if mode == "filter_calibrate" else None
            resume = None
            basis = library = None
            wanted = []
            if mode == "scan" and self.options.topup != "off":     # 所持数 vs this inventory (knowhow_scan.topup_plan)
                library = kb.load_inventory(self.inventory_path)
                basis = ks.library_basis(library)
            if mode == "scan" and self.options.keep:               # keep step: plan against the library + wanted list
                wanted = kb.load_wanted_from_profile(self.profile_path)
            if resume_path and mode == "scan" and scan_id:
                path = self.latest_partial(scan_id) if resume_path == "latest" else (self.run_dir / Path(str(resume_path)).name)
                if path is not None:                                          # private run records only
                    resume = json.loads(path.resolve().read_text(encoding="utf-8"))
        except Exception as exc:
            self.report("config_invalid", error=str(exc)[:200])
            return False
        self.mode = mode
        stamp = self.clock().strftime("%Y%m%dT%H%M%SZ")
        self.frames_dir = self.run_dir / f"{mode}-{stamp}"
        if mode == "calibrate":
            self.session = kc.CalibrationSession(calib, ContextOcr(context))
        elif mode == "filter_calibrate":
            self.session = kf.FilterCalibration(fcalib, ContextOcr(context))
        else:
            self.session = ks.ScanSession(self.options, ContextOcr(context), resume=resume, scan_id=scan_id,
                                          basis=basis, library=library if self.options.keep else None, wanted=wanted)
        return True

    def latest_partial(self, scan_id=None):
        """Newest partial belonging to this automatic scan; old user scans are never positional caches."""
        records = sorted(self.run_dir.glob("knowhow-scan-*-partial.json"))
        if not scan_id:
            return None
        for path in reversed(records):
            try:
                record = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if isinstance(record, dict) and record.get("scan_id") == scan_id:
                return path
        return None

    def save_frame(self, rgb, number):
        """Private copy of every observed capture (calibration evidence / scan audit)."""
        try:
            from PIL import Image

            self.frames_dir.mkdir(parents=True, exist_ok=True)
            Image.fromarray(rgb).save(self.frames_dir / f"frame-{number:04d}.png")
        except Exception:                      # evidence only: a failed save never changes the run
            LOGGER.exception("KnowhowScan frame save failed")

    def decision(self, context, image):
        """The session's decision for this capture (``_decision``), remembered for ``peek`` on the same capture."""
        decision = self._decision(context, image)
        self.last = (_image_digest(image), decision) if self.session is not None else None
        return decision

    def peek(self, image):
        """The decision already returned for this exact capture, else None; never observes. Maa tests a whole next
        list on one capture, so after SC.KnowhowScan.List.Back ([List.Guard, Want]) the ~50 later list-page nodes check
        this first and re-read the list-title OCR guard only for the wanted one (2026-10-23 round audit: a full round
        reached ~4.5 s at the last slot, close to the 5 s frame permit)."""
        if self.session is None or self.last is None:
            return None
        return self.last[1] if self.last[0] == _image_digest(image) else None

    def _decision(self, context, image):
        """The session's decision for this capture.

        A decision is consumed only when it was executed: an input decision once its node's Click/wheel was confirmed
        sent (``sent``, reached through SC.KnowhowScan.Sent.* after the action succeeded), a hold once the hold node
        matched. Until then an identical capture returns the cached decision without advancing the session, even when
        a Want recognition matched: the enclosing node may still not run (the launcher's frame guard refuses a frame
        that went stale during the slow first observation, 2026-10-12 live run). A capture that differs is observed
        as the next frame (counted in ``unconfirmed`` when an input was pending)."""
        if self.session is None:
            return None
        if self.session.final is not None and self.ocr_failed:
            return self.session.final                    # latched: never touch the native OCR again
        reader = self.session.read_texts
        if isinstance(reader, ContextOcr):
            reader.bind(context)
        digest = _image_digest(image)
        if self.cache is not None and not self.fresh:
            if self.cache[0] == digest or _same_screen(self.cache[2], image):
                return self.cache[1]
            if self.cache[1] is not None and self.cache[1].is_input:
                self.unconfirmed += 1
                LOGGER.warning("KnowhowScan: capture changed but %s was never confirmed sent", self.cache[1].kind)
        rgb = image[:, :, ::-1].copy()
        try:
            decision = self.session.observe(rgb)
        except OcrUnavailable as exc:
            self.ocr_failed = str(exc)
            LOGGER.error("KnowhowScan: OCR unavailable (%s): stopping without further native calls", exc)
            decision = self.session._decide(ks.Decision("stop", "ocr_failed", notes=(str(exc),)))
        if self.frames_dir is not None:
            self.save_frame(rgb, self.session.frames)
        self.cache, self.fresh = (digest, decision, image), False
        return decision

    def want(self, context, image, p):
        """Custom recognition: True when this capture's decision matches ``p`` (an input step, a hold or exit).
        A match never consumes an input decision (see ``decision``); only ``sent`` does."""
        state = p.get("is")
        if state is not None:
            if self.session is None:
                return state == "halted"
            final = self.session.final
            return {"active": final is None, "finished": final is not None,
                    "halted": final is not None and final.kind == "stop"}.get(state, False)
        decision = self.peek(image) if p.get("peek") else self.decision(context, image)
        if decision is None:
            return False
        want = p.get("want")
        if want in ("hold", "settle"):     # settle: a wheel's settle check (short re-capture, List.Settle)
            ok = decision.kind == "hold" and (want == "hold" or decision.reason in ks.SETTLE_REASONS)
            if ok:
                self.fresh = True  # no input: the hold node re-captures and that capture is observed afresh
            return ok
        if want not in ks.INPUT_KINDS:
            return False           # a stop never matches an input node: SC.KnowhowScan.Halted ends without input
        return decision.kind == want and all(getattr(decision, k) == p[k] for k in ("key", "row", "col", "direction")
                                             if k in p)

    def sent(self, context, p):
        """SC.KnowhowScan.Sent.*: the Want-bound Click/wheel node's action succeeded (the controller confirmed the
        send), so the cached decision is consumed and the next capture is a new observation even if identical."""
        del context, p
        if self.cache is None or self.cache[1] is None or not self.cache[1].is_input:
            LOGGER.warning("KnowhowScan: input confirmation without a pending input decision")
        self.fresh = True
        self.retries = 0
        return True

    MAX_RETRIES = 3

    def retry(self, context, p):
        """SC.KnowhowScan.Retry (on_error of every input node): re-capture and re-recognise after an input the
        controller proved it never sent (denied / refused with attempted false, e.g. the capture outlived the frame-age
        limit during the slow first observation, 2026-10-13 kh-full3). At most ``MAX_RETRIES`` per pending decision; a
        sent or uncertain input, or an unknown history, fails into Abort instead."""
        del context, p
        if self.session is None or self.cache is None or self.cache[1] is None or not self.cache[1].is_input or self.fresh:
            return False
        try:
            last = (self.click_history() or [None])[-1] if self.click_history is not None else None
        except Exception:
            last = None
        provably_unsent = last is not None and (last.get("result") == "denied" or (
            last.get("result") == "refused" and last.get("attempted") is False))
        if not provably_unsent or self.retries >= self.MAX_RETRIES:
            return False
        self.retries += 1
        LOGGER.warning("KnowhowScan: %s was not sent (%s); re-capturing (%d/%d)", self.cache[1].kind, last.get("reason"),
                       self.retries, self.MAX_RETRIES)
        return True

    def finish(self, context, p):
        """At home after the list was left: private run record, inventory and UI module (flagged when partial)."""
        del context, p
        if self.session is None:
            self.report("not_started")
            return False
        self.result = result = self.session.result()
        now = self.clock()
        stamp = now.strftime("%Y%m%dT%H%M%SZ")
        self.run_dir.mkdir(parents=True, exist_ok=True)
        frames = None if self.frames_dir is None else str(self.frames_dir)
        if self.mode == "filter_calibrate":
            record = self.run_dir / f"knowhow-filter-calibrate-{stamp}{'-partial' if result['partial'] else ''}.json"
            record.write_text(json.dumps({**result, "frames_dir": frames, "unconfirmed_inputs": self.unconfirmed},
                                         ensure_ascii=False, indent=1, default=str), encoding="utf-8")
            self.report("filter_calibrated" if not result["partial"]
                        else f"partial:{result['soft_reason'] or result['outcome']}", mode="filter_calibrate",
                        record=str(record), frames_dir=frames, unconfirmed_inputs=self.unconfirmed,
                        bottom=result["bottom"], down_step_px=result["down_step_px"], up_step_px=result["up_step_px"],
                        states=len(result["states"]))
            return not result["partial"]
        if self.mode == "calibrate":
            record = self.run_dir / f"knowhow-calibrate-{stamp}{'-partial' if result['partial'] else ''}.json"
            record.write_text(json.dumps({**result, "frames_dir": frames, "unconfirmed_inputs": self.unconfirmed}, ensure_ascii=False, indent=1, default=str),
                              encoding="utf-8")
            grid, detail = result["grid"], result["detail"]
            self.report("calibrated" if not result["partial"] else f"partial:{result['soft_reason'] or result['outcome']}",
                        mode="calibrate", record=str(record), frames_dir=frames, scan_ready=result["scan_ready"],
                        unconfirmed_inputs=self.unconfirmed,
                        grid_step_px=grid["step_px"], grid_step_rows=grid["step_rows"], grid_whole_rows=grid["whole_rows"],
                        grid_bottom=grid["bottom"], grid_up_step_px=grid["up_step_px"], detail_step_px=detail["step_px"],
                        detail_min_row_overlap=detail["min_row_overlap"], detail_starts_at_top=detail["starts_at_top"])
            return not result["partial"]
        newest = result.get("mode") == "newest"
        if newest:      # never a resume record of the full scan (always partial: only the top tiles in 獲得順)
            record = self.run_dir / f"knowhow-newest-{stamp}.json"
        else:
            record = self.run_dir / f"knowhow-scan-{stamp}{'' if not result['partial'] else '-partial'}.json"
        record.write_text(json.dumps(result, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
        summary = None
        if self.write_inventory and (result["books"] or result["grid"]["count"] or result.get("topup")):
            inv = kb.load_inventory(self.inventory_path)
            summary = ks.apply_to_inventory(result, inv, scanned_at=now.isoformat(timespec="seconds"))
            kb.save_inventory(inv, self.inventory_path)
            kb.export_ui_module(inv, self.ui_path)
        soft = result["soft_reason"]
        if newest and soft in ("library_up_to_date", "nothing_pending") and not result["books_opened"] \
                and not result["stopped"]:
            done, status = True, soft          # a top-up found nothing new (left without sorting)
        elif newest:
            done = (soft == "newest_done" and not result["stopped"] and not result["sort_restore_needed"]
                    and all(kb.KnowhowBookRecord.from_dict(b).complete for b in result["books"]))
            status = ("newest_read" if done else f"needs_full_scan:{soft}" if soft in ks.FULL_SCAN_REASONS
                      else f"partial:{soft or result['outcome']}")
            if (result.get("topup") or {}).get("mode") == "prefer":
                # the host's 扫描ノウハウ outcomes (UiKnowhowScan): a top-up instead of the full scan is a scan
                status = "scanned" if done else f"partial:{soft or result['outcome']}"
        else:
            done = not result["partial"]
            status = "scanned" if done else f"partial:{result['outcome']}"
        self.report(status, mode="scan", newest=result.get("newest"), topup=result.get("topup"),
                    record=str(record), frames_dir=frames, inventory=summary, unconfirmed_inputs=self.unconfirmed, books=len(result["books"]),
                    grid_count=result["grid"]["count"], grid_complete=result["grid_complete"],
                    sort_restore_needed=result["sort_restore_needed"], review=review_summary(result),
                    keep=keep_summary(result.get("keep")))
        return done

    def stop(self, context, p):
        """Terminal node of every failure path: keep what was read (flagged partial) and report once."""
        del context
        reason = p.get("reason", "stop")
        if self.outcome is None:
            if self.session is not None and self.result is None and (
                    self.session.books or getattr(self.session, "grid", None)
                    or getattr(self.session, "grid_steps", None)):
                self.finish(None, {})
            extra = {}
            if reason == "abort":     # no recovery path ran: say where the game was left
                extra = {"left_in_place": True, "note": "已停止且未回首页：游戏仍停在当前页面，不再输入，需手动返回"}
            self.report(f"stopped:{reason}", previous=self.outcome, **extra)
        return False

    def flush_on_task_end(self, capture_fail_streak=0, stopped_by=None):
        """The job ended without this scan's own stop/finish (2026-10-12 live: the desktop locked mid-detail, every capture
        failed, Maa could not evaluate any node, so SC.KnowhowScan.Abort never ran): keep what was read as a partial
        record and report why, once. Never sends input."""
        if self.session is None or self.outcome is not None:
            return False
        if capture_fail_streak:
            reason = f"host_capture_failed_streak={capture_fail_streak}"
        else:
            reason = "task_ended_before_report" if not stopped_by else f"stopped:{stopped_by}"
        self.stop(None, {"reason": reason})
        return True


def review_summary(result) -> dict:
    """Owned-card style confirmation split: complete books without flags are accepted automatically; only books with
    unknowns (clipped / unread rows, Lv5 count disagreeing with the tile, merge gaps) or OCR spelling variants are
    listed for the user to check."""
    accepted, review = 0, []
    for book in result.get("books") or ():
        record = kb.KnowhowBookRecord.from_dict(book)
        flags = sorted(set(record.unknowns) | {f"row_variant:{r.get('name')}" for r in book.get("rows") or ()
                                                 if isinstance(r, dict) and r.get("variants")})
        if record.complete and not flags:
            accepted += 1
        else:
            review.append({"grid_index": book.get("grid_index"), "title": record.title, "flags": flags[:8]})
    return {"auto_accepted": accepted, "needs_review": len(review), "review": review[:50]}


def keep_summary(keep) -> dict | None:
    """The keep step for the report / UI: what was locked, what would be sold, and an unconfirmed lock."""
    if not keep:
        return None
    titles = {v.get("grid_index"): v.get("title") for v in keep.get("verdicts") or ()}
    return {"settings": keep.get("settings"), "outcome": keep.get("outcome"), "sell_executor": keep.get("sell_executor"),
            "locked": [{"grid_index": i, "title": titles.get(i)} for i in keep.get("locked") or ()],
            "would_sell": [{"grid_index": i, "title": titles.get(i)} for i in keep.get("would_sell") or ()],
            "uncertain": keep.get("uncertain"), "presses": keep.get("presses"), "counts_ok": keep.get("counts_ok"),
            "synced": keep.get("synced"),
            "verdicts": [{k: v.get(k) for k in ("grid_index", "title", "action", "reason", "text")}
                         for v in keep.get("verdicts") or ()]}


RUNTIME = KnowhowScanRuntime()


class _Recognition(CustomRecognition):
    def __init__(self, runtime=RUNTIME):
        super().__init__()
        self.rt = runtime

    def analyze(self, context, argv):
        p = _params(argv.custom_recognition_param)
        try:
            ok = self.rt.want(context, argv.image, p)
        except Exception:
            LOGGER.exception("KnowhowScan want failed")
            return None
        if not ok:
            return None
        roi = argv.roi
        box = (int(roi[0]), int(roi[1]), max(1, int(roi[2])), max(1, int(roi[3]))) if roi is not None else (0, 0, 1, 1)
        return CustomRecognition.AnalyzeResult(box=box, detail={"want": p})


class _Action(CustomAction):
    METHOD = ""

    def __init__(self, runtime=RUNTIME):
        super().__init__()
        self.rt = runtime

    def run(self, context, argv):
        try:
            return bool(getattr(self.rt, self.METHOD)(context, _params(argv.custom_action_param)))
        except Exception:
            LOGGER.exception("KnowhowScan %s failed", self.METHOD)
            return False


