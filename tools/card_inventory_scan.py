#!/usr/bin/env python3
"""Offline 「持有卡牌」 scan: recognise card thumbnails in saved 1280x720 frames.

Reads only local files: frames the user already captured (e.g. a read-only recording of the in-game idol list) and the
local wiki icon set in ``ui/game-assets/``. No device, no input, no network. Writes the reviewed-import file
``ui/game-assets/inventory-scan.js`` (gitignored, CSP-safe ES module) that the panel's 持有卡牌 dialog offers for
review; nothing is added to 持有卡牌 until the user confirms there.

Usage::

    python tools/card_inventory_scan.py --layout idol_list FRAME.png [FRAME.png ...]
    python tools/card_inventory_scan.py --layout unit_formation --dry-run FRAME.png     # print only
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agent.core import card_inventory as ci  # noqa: E402
from agent.core import owned_levels as ol  # noqa: E402

OUT_FILE = ROOT / "ui" / "game-assets" / "inventory-scan.js"
MAX_FRAMES = 400


def is_gitignored(path: Path) -> bool:
    from tools.local_output import portable_output_allowed
    if portable_output_allowed(path, ROOT):
        return True
    try:
        result = subprocess.run(["git", "check-ignore", "-q", str(path)], cwd=ROOT, capture_output=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def scan(frames, layout, index=None):
    from PIL import Image

    index = index or ci.CardIndex.from_assets()
    results, cards = [], {}
    for path in frames:
        with Image.open(path) as image:
            result = ci.recognise(image, index, layout)
        results.append({"file": Path(path).name, "layout": layout, "accepted": len(result["accepted"]),
                        "rejected": result["rejected"]})
        for tile in result["tiles"]:
            if tile["status"] != "accepted":
                continue
            entry = cards.setdefault(tile["card_id"], {"id": tile["card_id"], "score": 0.0, "verify": 0.0, "confidence": 0.0,
                                                       "frames": 0})
            entry["score"] = max(entry["score"], tile["score"])
            entry["verify"] = max(entry["verify"], tile["verify"])
            # thumbnail-match confidence (owned_levels.match_confidence; the UI auto-applies >= AUTO_ACCEPT_CONFIDENCE)
            entry["confidence"] = max(entry["confidence"], ol.match_confidence(tile))
            entry["frames"] += 1
    return {"version": 1, "generated_by": "tools/card_inventory_scan.py", "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "layout": layout, "frames": results, "cards": sorted(cards.values(), key=lambda c: c["id"]),
            "rejected_tiles": sum(r["rejected"] for r in results)}


def read_module(out_file=OUT_FILE):
    """The previously written scan, or None."""
    path = Path(out_file)
    if not path.is_file():
        return None
    text = path.read_text(encoding="utf-8")
    start = text.find("export default ")
    return json.loads(text[start + len("export default "):].rstrip().rstrip(";")) if start >= 0 else None


def merge(old, new):
    """Union of two scans (cards keep the best score / verify and add up frames)."""
    if not old:
        return new
    cards = {c["id"]: dict(c) for c in old.get("cards", [])}
    for card in new["cards"]:
        cur = cards.setdefault(card["id"], {"id": card["id"], "score": 0.0, "verify": 0.0, "frames": 0})
        cur["score"], cur["verify"] = max(cur["score"], card["score"]), max(cur["verify"], card["verify"])
        if card.get("confidence") is not None or cur.get("confidence") is not None:   # an old scan without it stays low
            cur["confidence"] = max(cur.get("confidence") or 0.0, card.get("confidence") or 0.0)
        cur["frames"] += card["frames"]
    return {**new, "layout": "mixed" if old.get("layout") != new["layout"] else new["layout"],
            "frames": [*old.get("frames", []), *new["frames"]], "cards": sorted(cards.values(), key=lambda c: c["id"]),
            "rejected_tiles": old.get("rejected_tiles", 0) + new["rejected_tiles"]}


def write_module(data, out_file=OUT_FILE):
    out_file = Path(out_file).resolve()
    if out_file != OUT_FILE.resolve():
        raise ValueError(f"只能写到 {OUT_FILE.relative_to(ROOT).as_posix()}")
    if not is_gitignored(out_file):
        raise ValueError("ui/game-assets/ 未被 .gitignore 忽略，拒绝写入")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(data, ensure_ascii=False, indent=1)
    out_file.write_text("// Generated by tools/card_inventory_scan.py; local, gitignored. Suggestions for review only.\n"
                        f"export default {text};\n", encoding="utf-8", newline="\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("frames", nargs="+", help="saved 1280x720 PNG frames")
    parser.add_argument("--layout", choices=sorted(ci.LAYOUTS), default="idol_list")
    parser.add_argument("--dry-run", action="store_true", help="print the result; write nothing")
    parser.add_argument("--append", action="store_true", help="merge into the existing inventory-scan.js")
    args = parser.parse_args(argv)
    if len(args.frames) > MAX_FRAMES:
        parser.error(f"最多 {MAX_FRAMES} 帧")
    try:
        data = scan(args.frames, args.layout)
        if args.append:
            data = merge(read_module(), data)
        if not args.dry_run:
            write_module(data)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    summary = {"cards": len(data["cards"]), "rejected_tiles": data["rejected_tiles"], "frames": data["frames"],
               "written": None if args.dry_run else OUT_FILE.relative_to(ROOT).as_posix()}
    sys.stdout.buffer.write((json.dumps(summary, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
