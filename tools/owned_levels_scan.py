#!/usr/bin/env python3
"""Offline owned Lv / 凸 scan of saved アイドル一覧 frames.

Reads only local files (frames the user already captured, the local card icons in ``ui/game-assets/`` and the local
OCR model).  No device, no input, no network.  Writes the reviewed-import file ``ui/game-assets/owned-levels.js``
(gitignored): ``details`` has the ``prefs.owned_cards.details`` shape and ``cards`` the per-card confidence and the
source frame.  This tool never writes the user profile.  The resources page applies readings with
``confidence >= auto_accept_confidence`` (``owned_levels.AUTO_ACCEPT_CONFIDENCE``) automatically, never over a value the
user set, and lists the rest under 「需要你确认」.

Usage::

    python tools/owned_levels_scan.py FRAME.png [FRAME.png ...]
    python tools/owned_levels_scan.py --dry-run FRAME.png
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agent.core import card_inventory as ci  # noqa: E402
from agent.core import owned_levels as ol  # noqa: E402
from tools.card_inventory_scan import is_gitignored  # noqa: E402

OUT_FILE = ROOT / "ui" / "game-assets" / "owned-levels.js"
DEFAULT_MODEL = ROOT / "dev_assets" / "private" / "models" / "ppocr_v6_small"
MAX_FRAMES = 400


def scan(frames, *, index=None, ocr=None, model_dir=DEFAULT_MODEL):
    from PIL import Image

    index = index or ci.CardIndex.from_assets()
    ocr = ocr or ol.maa_ocr(model_dir)
    records, per_frame = [], []
    for path in frames:
        path = Path(path)
        name = f"{path.parent.name}/{path.name}"
        with Image.open(path) as image:
            recs = ol.read_frame(image, index, ocr, frame_name=name)
        records += recs
        per_frame.append({"file": name, "accepted": sum(r["status"] == "accepted" for r in recs),
                          "rejected": sum(r["status"] != "accepted" for r in recs)})
    merged = ol.merge_readings(records)
    reasons: dict[str, int] = {}
    for rec in records:
        for reason in rec.get("reasons", ()):
            key = reason.split(":", 1)[0] + ":" + reason.split(":", 1)[1].split(":")[0] if ":" in reason else reason
            reasons[key] = reasons.get(key, 0) + 1
    return {"version": 1, "generated_by": "tools/owned_levels_scan.py",
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "note": "Stars = limit break (gold 1-3, purple 4); P cards have no level. The UI auto-applies cards with "
                    "confidence >= auto_accept_confidence (never over a user-set value); the rest need review.",
            "auto_accept_confidence": ol.AUTO_ACCEPT_CONFIDENCE,
            "frames": per_frame, "cards": merged["cards"], "conflicts": merged["conflicts"],
            "rejected_tiles": merged["rejected"], "rejected_reasons": dict(sorted(reasons.items())),
            "details": ol.details_for_import(merged)}


def write_module(data, out_file=OUT_FILE):
    out_file = Path(out_file).resolve()
    if out_file != OUT_FILE.resolve():
        raise ValueError(f"只能写到 {OUT_FILE.relative_to(ROOT).as_posix()}")
    if not is_gitignored(out_file):
        raise ValueError("ui/game-assets/ 未被 .gitignore 忽略，拒绝写入")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text("// Generated by tools/owned_levels_scan.py; local, gitignored. High-confidence readings are auto-applied by the UI.\n"
                        f"export default {json.dumps(data, ensure_ascii=False, indent=1)};\n",
                        encoding="utf-8", newline="\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("frames", nargs="+", help="saved 1280x720 PNG frames of アイドル一覧 (P or S tab)")
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL, help="local OCR model directory")
    parser.add_argument("--dry-run", action="store_true", help="print the summary; write nothing")
    args = parser.parse_args(argv)
    if len(args.frames) > MAX_FRAMES:
        parser.error(f"最多 {MAX_FRAMES} 帧")
    try:
        data = scan(args.frames, model_dir=args.model)
        if not args.dry_run:
            write_module(data)
    except (OSError, ValueError, RuntimeError) as error:
        parser.error(str(error))
    cards = data["cards"]
    summary = {"cards": len(cards), "p": sum(c.startswith("1") for c in cards), "s": sum(c.startswith("2") for c in cards),
               "conflicts": len(data["conflicts"]), "rejected_tiles": data["rejected_tiles"],
               "rejected_reasons": data["rejected_reasons"], "frames": len(data["frames"]),
               "written": None if args.dry_run else OUT_FILE.relative_to(ROOT).as_posix()}
    sys.stdout.buffer.write((json.dumps(summary, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
