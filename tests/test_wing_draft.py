"""Contract tests for the W.I.N.G. draft pipeline and its offline OCR feasibility tool (no Maa, no input)."""
from __future__ import annotations

import json
import unittest
from pathlib import Path
from unittest import mock

from tools import wing_sample_ocr as wso

ROOT = Path(__file__).resolve().parent.parent
DRAFT = ROOT / "assets/resource/base/pipeline/wing_draft.json"


class DraftPipelineContract(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.pipeline = json.loads(DRAFT.read_text(encoding="utf-8"))
        cls.samples = json.loads(wso.SAMPLE_MAP.read_text(encoding="utf-8"))

    def test_draft_contract(self):
        self.assertEqual(wso.validate_draft(self.pipeline), [])

    def test_every_node_disabled_and_recognition_only(self):
        for name, node in self.pipeline.items():
            self.assertTrue(name.startswith("SC.Wing."), name)
            self.assertIs(node["enabled"], False, name)
            self.assertNotIn("action", node, name)
            self.assertNotIn("next", node, name)
            self.assertIn(node["recognition"], {"OCR", "ColorMatch", "And", "Or"}, name)

    def test_no_live_wiring(self):
        """SC.Wing.* lives only in wing_draft.json (recognition) and wing.json (navigation framework, generated by
        tools/wing_nav_build.py, 2026-10-05). Neither is wired to a task/interface/policy/action table, and wing.json
        cannot send input: every node disabled, no input action, only the SC.Wing.* Agent actions, whose Act gate
        refuses while wing_nav.LIVE_INPUT_ENABLED is False."""
        from agent.core import wing_nav
        from tools.check_project import INPUT_ACTIONS
        navigation = ROOT / "assets/resource/base/pipeline/wing.json"
        interface = (ROOT / "assets/interface.json").read_text(encoding="utf-8")
        self.assertNotIn("SC.Wing.", interface)
        for path in (ROOT / "assets/resource/base/pipeline").rglob("*.json"):
            if path.name not in (DRAFT.name, navigation.name):
                self.assertNotIn("SC.Wing.", path.read_text(encoding="utf-8"), path.name)
        for path in list((ROOT / "assets/tasks").rglob("*.json")) + [ROOT / "project_policy.json"]:
            self.assertNotIn("SC.Wing.", path.read_text(encoding="utf-8"), path.name)
        # The action table binds the generated SC.Wing.Click.* nodes to wing-* actions. Since 2026-10-11 the generator
        # (tools/wing_nav_build.py --enable-actions) enables exactly the verified targets; unverified ones stay off.
        from agent.core import wing_nav as nav
        verified = {nav.action_id(i) for i, (_, ok) in nav.TARGETS.items() if ok}
        table = json.loads((ROOT / "assets/input/pipeline_actions.json").read_text(encoding="utf-8"))
        for action in table["actions"]:
            if any(n.startswith("SC.Wing.") for n in action["nodes"]):
                self.assertTrue(action["id"].startswith("wing-"), action["id"])
                if action["enabled"]:
                    self.assertIn(action["id"], verified)
                self.assertTrue(all(n.startswith("SC.Wing.Click.") for n in action["nodes"]), action["id"])
        nodes = json.loads(navigation.read_text(encoding="utf-8"))
        allowed = {"SC.Wing.Begin", "SC.Wing.Stop", "SC.Wing.Finish"}
        for name, node in nodes.items():
            self.assertTrue(name.startswith("SC.Wing."), name)
            self.assertIs(node.get("enabled"), False, name)
            if node.get("action", "DoNothing") in INPUT_ACTIONS:
                self.assertEqual((node["action"], name.startswith("SC.Wing.Click.")), ("Click", True), name)
            if node.get("action") == "Custom":
                self.assertIn(node["custom_action"], allowed, name)
        self.assertFalse(wing_nav.LIVE_INPUT_ENABLED)

    def test_sample_map_matches_guards(self):
        self.assertEqual(wso.validate_sample_map(self.samples, self.pipeline), [])

    def test_ocr_expected_are_valid_regex(self):
        import re
        for name, node in self.pipeline.items():
            for pattern in node.get("expected", []):
                re.compile(pattern)

    def test_danger_anchor_is_never_a_positive_guard(self):
        guards = wso.screen_guards(self.pipeline)
        for refs in guards.values():
            self.assertNotIn("SC.Wing.Anchor.Reward.RerollDanger", refs)

    def test_validate_draft_rejects_enabled_click_and_template(self):
        bad = {"SC.Wing.X": {"recognition": "OCR", "roi": [0, 0, 10, 10], "action": "Click"},
               "SC.Wing.Y": {"recognition": "TemplateMatch", "template": "wing/x.png", "enabled": False},
               "SC.Wing.Z": {"recognition": "OCR", "roi": [1200, 700, 100, 40], "enabled": False}}
        errors = "\n".join(wso.validate_draft(bad))
        self.assertIn("enabled=false", errors)
        self.assertIn("must not act", errors)
        self.assertIn("templates", errors)
        self.assertIn("roi outside", errors)


class ToolHelpers(unittest.TestCase):
    def test_canvas_ratio(self):
        for size in [(420, 236), (560, 315), (693, 390), (700, 394), (800, 450), (350, 197)]:
            self.assertTrue(wso.is_canvas_ratio(size), size)
        self.assertFalse(wso.is_canvas_ratio((701, 884)))

    def test_read_match_ignores_spacing(self):
        self.assertTrue(wso.read_match("+10 000", "+10000"))
        self.assertFalse(wso.read_match("+1000", "+10000"))
        self.assertFalse(wso.read_match(None, "1"))

    def test_evaluate_guard_logic_with_fake_recognizer(self):
        pipeline = {
            "SC.Wing.Anchor.A": {"recognition": "OCR", "roi": [0, 0, 10, 10], "expected": ["a"], "enabled": False},
            "SC.Wing.Anchor.B": {"recognition": "OCR", "roi": [0, 0, 10, 10], "expected": ["b"], "enabled": False},
            "SC.Wing.Read.N": {"recognition": "OCR", "roi": [0, 0, 10, 10], "enabled": False},
            "SC.Wing.Screen.One": {"recognition": "And", "all_of": ["SC.Wing.Anchor.A", "SC.Wing.Anchor.B"], "enabled": False},
            "SC.Wing.Screen.Two": {"recognition": "And", "all_of": ["SC.Wing.Anchor.B"], "enabled": False},
        }
        sample_map = {"sample_dir": ".", "name_pattern": "{id}", "kinds": {"One": ["s1"], "Two": ["s2"]},
                      "read_truth": {"N": {"s1": "7"}}}
        # s1 shows A, B and text "7"; s2 shows only B -> Two's guard also fires on s1 (false positive).
        seen = {"s1": {"a", "b", "7"}, "s2": {"b"}}

        class Fake:
            input_attempts = 0

            def run(self, image, node):
                want = node.get("expected", [None])[0]
                if want is None:
                    return {"hit": True, "texts": [{"text": "7"}] if "7" in seen[image] else [], "count": None}
                return {"hit": want in seen[image], "texts": [], "count": None}

        with mock.patch.object(wso, "load_canvas", side_effect=lambda path: Path(path).name):
            report = wso.evaluate(pipeline, sample_map, Fake())
        self.assertEqual(report["screens"]["One"]["recall"], "1/1")
        self.assertEqual(report["screens"]["Two"]["false_positive_kinds"], ["One"])
        self.assertEqual(report["screens"]["One"]["false_positive_kinds"], [])
        self.assertEqual(report["reads"]["N"]["exact"], "1/1")
        self.assertEqual(report["input_attempts"], 0)


if __name__ == "__main__":
    unittest.main()
